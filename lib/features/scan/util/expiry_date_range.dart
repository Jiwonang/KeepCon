/// scan — 유효기간으로 **고를 수 있는 범위**.
///
/// 값 자체는 원래 `gifticon_form_page.dart`의 `showDatePicker` 호출부에
/// `DateTime(2020)`·`DateTime(2035)`로 박혀 있었다. 한곳으로 올린 이유는 이 범위를
/// **보는 곳이 둘**이기 때문이다 — 피커의 경계와, 피커를 여는 시작 위치(클램프).
/// 둘이 갈라지면 "고를 수 없는 값이 프리필돼 있는" 상태가 조용히 생긴다.
///
/// ## 지난 날짜 판정은 여기 없다
///
/// 계약 정본 `lib/shared/util/expiry_policy.dart`의 `isExpiredByDate`를 쓴다.
/// **여기서 다시 구현하지 않는다** — `tool/check_ssot.sh`가 그 함수를 가드에 넣어 둔
/// 근거가 "승격 전 이 계산이 `lib/features` 안에 **네 벌** 있었고, 그중 하나는 시분초를
/// 절삭해 같은 기프티콘을 두고 화면과 통계가 다른 답을 냈다"이다.
///
/// ⚠️ 이 파일에도 한때 `isPastExpiry`라는 같은 술어가 있었다. 이름이 달라 SSOT 가드가
/// 보지 못했고(가드는 이름으로 검사한다) CI를 그대로 통과했다 — 다섯 번째 사본이 될
/// 뻔한 것을 리뷰에서 잡았다. 게다가 계약 쪽이 더 낫다: UTC로 정규화해 DST가 낀
/// 구간에서 하루가 어긋나는 것까지 막는다(웹 빌드는 사용자 브라우저 타임존에서 돈다).
/// **만료 관련 판정이 필요하면 먼저 `expiry_policy.dart`를 찾아볼 것.**
///
/// ## 왜 파서를 이 범위로 제한하지 않는가
///
/// `GifticonOcrParser`는 **이미지에 적힌 것을 그대로 읽는 것이 일이다.** 2016년이
/// 인쇄돼 있으면 2016년을 내야 하고, 실제로 그렇게 동작한다(픽스처 테스트가
/// `expect(result.expiryDate, DateTime(2016, 2, 12))`로 못박고 있다). 파서가 범위를
/// 강제하면 원본과 다른 값을 내는 셈이라, 사용자가 화면에서 확인·수정할 기회 자체가
/// 사라진다. 그래서 범위는 **화면의 책임**이다.
library;

/// 유효기간으로 고를 수 있는 가장 이른 날.
///
/// 지난 날짜를 **허용하는** 하한이다. `GifticonStatus`의 `available → expired` 전이가
/// 계약에 정의돼 있고, 만료된 기프티콘도 목록에서 걸러지지 않으므로(만료 표시만 붙는다)
/// 이미 만료된 것을 기록해 두는 것도 정당한 사용이다. 대신 지난 날짜에는 화면이
/// 안내를 띄운다.
final DateTime expirySelectableFrom = DateTime(2020);

/// 유효기간으로 고를 수 있는 가장 늦은 날.
///
/// ⚠️ **이 값은 2035-01-01이다.** `DateTime(2035)`는 그 해 1월 1일이라, 2035년의
/// 나머지 364일은 **고를 수 없다.** 연말(`DateTime(2035, 12, 31)`)로 넓히는 것이
/// 맞지만 그것은 화면에서 고를 수 있는 범위가 달라지는 변경이라 소유자 확인이
/// 필요하다 — 확인 전까지 동작을 그대로 둔다. 2035년은 아직 멀어 급하지 않다.
///
/// 파서는 실제로 이 위를 넘는 값을 낸다 — 연도 패턴이 `20\d{2}`(2000~2099)와
/// `2000 + \d{2}`라 `유효기간 2099.12.31`은 2099년으로, 일련번호에 섞인 `40.12.31`은
/// 2040년으로 읽힌다. 그래서 상한 쪽 클램프도 하한과 똑같이 필요하다.
final DateTime expirySelectableTo = DateTime(2035);
