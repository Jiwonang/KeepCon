/// KeepCon 공유 계약 — 유효기간으로 **고를 수 있는 범위** (단일 정본 / SSOT).
///
/// 값 자체는 원래 `gifticon_form_page.dart`의 `showDatePicker` 호출부에
/// `DateTime(2020)`·`DateTime(2035)`로 박혀 있었다. 처음 한곳으로 올린 이유는 이 범위를
/// **보는 곳이 둘**이었기 때문이다 — 피커의 경계와, 피커를 여는 시작 위치(클램프).
/// 둘이 갈라지면 "고를 수 없는 값이 프리필돼 있는" 상태가 조용히 생긴다.
///
/// ## 왜 계약(lib/shared)으로 승격했는가
/// 소비자가 **페이지를 넘었다.** scan의 등록 폼에 이어 유효기간 연장
/// (`lib/shared/widgets/extend_expiry_dialog.dart`)이 같은 상한을 봐야 하고, 그 다이얼로그는
/// main·share 두 상세 화면이 함께 쓴다. 계약이 페이지(`lib/features/scan`)를 향해 의존할 수는
/// 없으므로, 다이얼로그를 계약으로 올리는 순간 이 상수도 함께 올라와야 한다.
///
/// 페이지에 남겨 두면 다음 사람은 둘 중 하나를 한다 — 교차 페이지 import(이 저장소에 선례가
/// 없다)를 만들거나, **사본을 뜬다.** 후자가 실제 위험이다: 이 저장소는 `isExpiredByDate`가
/// `lib/features` 안에 **네 벌** 있었고 그중 하나가 시분초를 절삭해 같은 기프티콘을 두고 화면과
/// 통계가 다른 답을 낸 전력이 있다(아래 절 참조). 재발 방어선은 `tool/check_ssot.sh`다.
///
/// ## 지난 날짜 판정은 여기 없다
///
/// 계약 정본 `lib/shared/util/expiry_policy.dart`의 `isExpiredByDate`를 쓴다.
/// **여기서 다시 구현하지 않는다** — `tool/check_ssot.sh`가 그 함수를 가드에 넣어 둔
/// 근거가 "승격 전 이 계산이 `lib/features` 안에 **네 벌** 있었고, 그중 하나는 시분초를
/// 절삭해 같은 기프티콘을 두고 화면과 통계가 다른 답을 냈다"이다.
///
/// ⚠️ 이 파일에도 한때 `isPastExpiry`라는 같은 술어가 있었다. 이름이 달라 SSOT 가드가
/// 보지 못했고(가드는 이름으로 검사한다) CI를 그대로 통과했다 — 다섯 번째 사본이 될
/// 뻔한 것을 리뷰에서 잡았다. 게다가 계약 쪽이 더 낫다: UTC로 정규화해 DST가 낀
/// 구간에서 하루가 어긋나는 것까지 막는다(웹 빌드는 사용자 브라우저 타임존에서 돈다).
/// **만료 관련 판정이 필요하면 먼저 `expiry_policy.dart`를 찾아볼 것.**
///
/// ## 왜 파서를 이 범위로 제한하지 않는가
///
/// `GifticonOcrParser`는 **이미지에 적힌 것을 그대로 읽는 것이 일이다.** 2016년이
/// 인쇄돼 있으면 2016년을 내야 하고, 실제로 그렇게 동작한다(픽스처 테스트가
/// `expect(result.expiryDate, DateTime(2016, 2, 12))`로 못박고 있다). 파서가 범위를
/// 강제하면 원본과 다른 값을 내는 셈이라, 사용자가 화면에서 확인·수정할 기회 자체가
/// 사라진다. 그래서 범위는 **화면의 책임**이다.
library;

/// 유효기간으로 고를 수 있는 가장 이른 날.
///
/// 지난 날짜를 **허용하는** 하한이다. `GifticonStatus`의 `available → expired` 전이가
/// 계약에 정의돼 있고, 만료된 기프티콘도 목록에서 걸러지지 않으므로(만료 표시만 붙는다)
/// 이미 만료된 것을 기록해 두는 것도 정당한 사용이다. 대신 지난 날짜에는 화면이
/// 안내를 띄운다.
///
/// ℹ️ **여기서는 월·일을 생략하는 것이 맞다** — 생략하면 1월 1일, 곧 그 해 첫날이라
/// 하한이 원하는 값과 같아진다. 상한([expirySelectableTo])의 "생략 금지" 경고는
/// **연말이 필요한 그쪽에만** 해당한다. 두 상수는 같은 규칙의 반대편이다.
final DateTime expirySelectableFrom = DateTime(2020);

/// 유효기간으로 고를 수 있는 가장 늦은 날.
///
/// **연말이라는 것이 이 값의 핵심이다.** 한때 `DateTime(2035)`였는데 그것은 그 해
/// **1월 1일**이라(월·일을 생략하면 1로 채워진다) 2035년의 나머지 364일을 고를 수
/// 없었다. "2035년까지"라고 읽히는 표기가 실제로는 "2035년 첫날까지"였던 것이라,
/// 연말로 명시해 표기와 동작을 맞췄다.
///
/// ⚠️ **월·일을 생략하지 마라.** 상한을 다른 해로 옮길 때 `DateTime(2040)`처럼
/// 쓰면 같은 결함이 그대로 재발한다. 그때도 `DateTime(2040, 12, 31)`로 쓴다.
/// 이 규칙은 `expiry_date_range_test.dart`가 지킨다(하한은 반대 — 위 참조).
///
/// **이 상한은 언젠가 지난다.** 지나면 피커가 내주는 날짜가 **전부 과거**가 되어
/// 새 기프티콘에 유효한 유효기간을 넣을 방법이 사라진다(2036년 시계로 재현 확인:
/// 값이 없으면 `initialDate`가 클램프돼 2035-12-31이 되고, `lastDate`도 같으므로
/// 고를 수 있는 모든 날이 과거다). 다가오면 다음 해 연말로 옮길 것.
///
/// 그 시점을 알려 주는 **자동 장치는 일부러 두지 않았다.** `DateTime.now()`를 읽는
/// 알람 테스트를 검토했으나, 코드가 아니라 달력이 바뀌어서 CI가 빨개지는 것은 이
/// 저장소가 PR #119에서 **결함으로 규정하고 제거한 것**이다. 의도된 알람이라도
/// 같은 양상이라 두지 않는다 — 대신 이 문단이 그 지식을 남긴다.
///
/// 파서는 실제로 이 위를 넘는 값을 낸다 — 연도 패턴이 `20\d{2}`(2000~2099)와
/// `2000 + \d{2}`라 `유효기간 2099.12.31`은 2099년으로, 일련번호에 섞인 `40.12.31`은
/// 2040년으로 읽힌다. 그래서 상한 쪽 클램프도 하한과 똑같이 필요하다.
final DateTime expirySelectableTo = DateTime(2035, 12, 31);
